# تهيئة المتغيرات الأولية
مجموع = 0
العداد = 0

# قراءة أول عدد من المستخدم
عدد = int(input("أدخل عدداً (أو 0 للتوقف): "))

# حلقة التكرار طالما أن العدد لا يساوي صفراً
while عدد != 0:
    مجموع += عدد
    العداد += 1
    
    # قراءة العدد التالي
    عدد = int(input("أدخل عدداً (أو 0 للتوقف): "))

# طباعة النتائج النهائية
print("-------------------------")
print(f"عدد الأرقام المدخلة: {العداد}")
print(f"مجموع الأعداد هو: {مجموع}")
